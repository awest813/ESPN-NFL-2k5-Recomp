"""Verify the pinned Xbox line capture; regenerate probes and compare raw replays.

Requires Pillow. The full crop comparison reports known mismatches, rather
than treating the limited probe checks as proof of complete coverage.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--write-header', action='store_true')
    parser.add_argument('--replay-prefix', help='Raw 640x480 BGRA dump prefix, relative to directory')
    parser.add_argument('--width-model', action='store_true', help='Compare the inferred rule against neighboring pinned widths')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'docs/references/nv2a-line-width.json').read_text(encoding='utf-8'))
    for key in ('capture', 'source'):
        item = manifest[key]
        path = args.directory / item['file']
        if key == 'source' and not path.exists():
            continue
        if hashlib.sha256(path.read_bytes()).hexdigest() != item['sha256']:
            raise ValueError(f'{key} hash mismatch: {path}')
        if key == 'source':
            text = path.read_text(encoding='utf-8')
            end = text.index('host.Begin(TestHost::PRIMITIVE_LINE_LOOP)')
            begin = text.rfind('constexpr float kVertices[][2]', 0, end)
            vertices = [[float(x), float(y)] for x, y in re.findall(
                r'\{([-\d.]+)f,\s*([-\d.]+)f\}', text[begin:end])]
            assert vertices == manifest['raw_xy'], 'Manifest geometry differs from the pinned source'
            begin = text.index('static constexpr uint32_t kPalette[]')
            values = re.findall(r'0x([0-9A-Fa-f]{8})', text[begin:text.index('};', begin)])
            assert values == manifest['diffuse_low_byte_r'], 'Manifest palette differs from the pinned source'
    reference = Image.open(args.directory / manifest['capture']['file']).convert('RGB')
    assert list(reference.size) == manifest['surface']
    ox, oy = manifest['origin']
    positions = [(math.trunc((x+ox)*16)/16, math.trunc((y+oy)*16)/16) for x, y in manifest['raw_xy']]
    cx, cy, cw, ch = manifest['crop']
    background = tuple(manifest['background'])
    mask = set()
    probes = []
    for y in range(cy, cy+ch):
        for x in range(cx, cx+cw):
            rgb = reference.getpixel((x, y))
            if rgb == background:
                continue
            mask.add((x, y))
            hits = []
            for a, b in zip(positions, positions[1:]+positions[:1]):
                dx, dy = b[0]-a[0], b[1]-a[1]
                length = math.hypot(dx, dy)
                px, py = x+.5-a[0], y+.5-a[1]
                t = (px*dx+py*dy)/length**2
                distance = abs(dx*py-dy*px)/length
                if 0 < t < 1 and distance < .6:
                    hits.append((t, distance, max(abs(dx), abs(dy))/length))
            if len(hits) == 1:
                t, distance, scale = hits[0]
                if .05 < t < .95 and distance < .46 and distance/scale > .52:
                    probes.append((x, y, *rgb))
    assert len(mask) == manifest['reference_foreground_pixels']
    assert len(probes) == manifest['expected_probes']
    mask_bytes = bytearray((cw*ch+7)//8)
    reference_rgb = []
    for y in range(cy, cy+ch):
        for x in range(cx, cx+cw):
            if (x, y) in mask:
                bit = (y-cy)*cw+x-cx
                mask_bytes[bit//8] |= 1 << (bit%8)
                reference_rgb.append(reference.getpixel((x, y)))
    header = ('/* Generated by tools/audit-line-reference.py from the pinned Xbox capture. */\n'
              '#ifndef NFL2K5_LINE_WIDTH_REFERENCE_H\n#define NFL2K5_LINE_WIDTH_REFERENCE_H\n'
              'static const float line_reference_xy[16][2]={\n'
              + ''.join(f'    {{{x:.9f}f,{y:.9f}f}},\n' for x, y in manifest['raw_xy'])
              + '};\nstatic const uint32_t line_reference_palette[8]={\n    '
              + ','.join('0x'+value+'u' for value in manifest['diffuse_low_byte_r'])
              + '\n};\ntypedef struct {uint16_t x,y;uint8_t r,g,b;} LineReferenceProbe;\n'
              + 'static const LineReferenceProbe line_reference_probes[]={\n'
              + ''.join('    {'+','.join(map(str, probe))+'},\n' for probe in probes)
              + '};\nenum {LINE_REFERENCE_X='+str(cx)+',LINE_REFERENCE_Y='+str(cy)
              + ',LINE_REFERENCE_W='+str(cw)+',LINE_REFERENCE_H='+str(ch)+'};\n'
              + 'static const uint8_t line_reference_mask[]={\n'
              + ''.join('    '+','.join(f'0x{v:02X}' for v in mask_bytes[i:i+24])+',\n'
                        for i in range(0, len(mask_bytes), 24))
              + '};\nstatic const uint8_t line_reference_rgb[][3]={\n'
              + ''.join('    {'+','.join(map(str, rgb))+'},\n' for rgb in reference_rgb)
              + '};\n#endif\n')
    path = ROOT / 'external/xboxrecomp/tests/sdlgpu_web/line_width_reference.h'
    if args.write_header:
        path.write_bytes(header.encode('utf-8'))
    assert path.read_text(encoding='utf-8') == header, 'Reference header is stale'
    print(f'PASS pinned Xbox capture: {len(mask)} foreground pixels, {len(probes)} independent diagonal probes')
    if args.width_model:
        for item in manifest['width_validation_captures']:
            path = args.directory / item['file']
            if hashlib.sha256(path.read_bytes()).hexdigest() != item['sha256']:
                raise ValueError(f'Width capture hash mismatch: {path}')
            image = Image.open(path).convert('RGB')
            assert image.size == reference.size
            width = item['width_register']/8
            expected = {(x, y) for y in range(cy, cy+ch) for x in range(cx, cx+cw)
                        if image.getpixel((x, y)) != background}
            predicted = set()
            if width > 0:
                for a, b in zip(positions, positions[1:]+positions[:1]):
                    dx, dy = b[0]-a[0], b[1]-a[1]
                    length_squared = dx*dx+dy*dy
                    extent = max(abs(dx), abs(dy))+.5*min(abs(dx), abs(dy))
                    for y in range(cy, cy+ch):
                        for x in range(cx, cx+cw):
                            px, py = x+.5-a[0], y+.5-a[1]
                            t = (px*dx+py*dy)/length_squared
                            if 0 <= t < 1 and abs(dx*py-dy*px) <= width*extent*.5:
                                predicted.add((x, y))
            print(f'Inferred model width {width:g}: reference={len(expected)} '
                  f'extra={len(predicted-expected)} missing={len(expected-predicted)}')
    if args.replay_prefix:
        for mode in ('gpu', 'software', '2d', '2d-software'):
            path = args.directory / f'{args.replay_prefix}-{mode}.argb'
            if not path.exists():
                continue
            image = Image.frombytes('RGBA', reference.size, path.read_bytes(), 'raw', 'BGRA').convert('RGB')
            actual = {(x, y) for y in range(cy, cy+ch) for x in range(cx, cx+cw)
                      if image.getpixel((x, y)) != background}
            shared = actual & mask
            close = sum(max(abs(a-b) for a, b in zip(reference.getpixel(p), image.getpixel(p))) <= 2 for p in shared)
            probe_failures = sum(max(abs(a-b) for a, b in zip(image.getpixel((x, y)), (r, g, b))) > 2
                                 for x, y, r, g, b in probes)
            print(f'{mode}: covered={len(shared)}/{len(mask)} extra={len(actual-mask)} '
                  f'missing={len(mask-actual)} RGB-within-2={close}/{len(shared)} '
                  f'probe-failures={probe_failures}/{len(probes)}')


if __name__ == '__main__':
    main()
