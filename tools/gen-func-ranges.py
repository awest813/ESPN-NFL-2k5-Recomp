"""Write the converted functions' address ranges for the interpreter.

    python tools/gen-func-ranges.py <analysis dir> <output .c>
    python tools/gen-func-ranges.py --generated <generated dir> <output .c>

src/interp/interp_setup.c compares each range of a mod pack's executable with
the executable the native code was converted from, and marks the functions
that differ so they run in the interpreter (src/interp/x86_interp.c).
"""
import argparse
import json
from pathlib import Path
import re


# The translator emits this metadata above each definition. The register-locals
# pass can insert register synchronization macros between the two.
# Numbered chunks hold translated functions. The dispatch and unresolved stub
# sources do not describe original function bodies.
DEFINITION = rb"void (?:sub_([0-9A-Fa-f]{8})(?:_gen)?|xbe_entry_point)\(void\)[ \t]*\r?\n\{"
FUNCTION = re.compile(
    rb"^ \* Original: 0x([0-9A-Fa-f]{8}) - 0x([0-9A-Fa-f]{8}) \([^\n]*\n"
    rb"(?: \* [^\n]*\n)* \*/\r?\n"
    rb"(?:#(?:undef|define) RECOMP_REGS_(?:OUT|IN)[^\n]*\n)*" + DEFINITION,
    re.MULTILINE)
FUNCTION_DEFINITION = re.compile(rb"^" + DEFINITION, re.MULTILINE)


def generated_ranges(directory):
    ranges = {}
    for chunk in sorted(directory.glob("recomp_[0-9][0-9][0-9][0-9].c")):
        code = chunk.read_bytes()
        matches = list(FUNCTION.finditer(code))
        if not matches or len(matches) != len(FUNCTION_DEFINITION.findall(code)):
            raise ValueError(f"{chunk}: a translated function is missing original range metadata")
        for match in matches:
            lo_text, hi_text, name_address = match.groups()
            lo, hi = int(lo_text, 16), int(hi_text, 16)
            if (name_address is not None and int(name_address, 16) != lo) or hi <= lo:
                raise ValueError(f"{chunk}: invalid original range at 0x{lo:08X}")
            if lo in ranges:
                raise ValueError(f"{chunk}: duplicate translated function at 0x{lo:08X}")
            ranges[lo] = hi
    if not ranges:
        raise ValueError(f"{directory}: no translated function ranges found")
    return sorted(ranges.items())


def analysis_ranges(directory):
    with (directory / "disasm/functions.json").open(encoding="utf-8") as source:
        funcs = json.load(source)
    ranges = {(int(f["start"], 16), int(f["end"], 16)) for f in funcs if f.get("end")}
    return sorted((lo, hi) for lo, hi in ranges if hi > lo)


def main(args):
    ranges = generated_ranges(args.source) if args.generated else analysis_ranges(args.source)
    out = args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by tools/gen-func-ranges.py. */",
             "#include <stdint.h>",
             "const uint32_t g_nfl2k5_func_ranges[][2] = {"]
    lines += ["    { 0x%08X, 0x%08X }," % r for r in ranges]
    lines.append("};")
    lines.append("const unsigned g_nfl2k5_func_range_count = sizeof g_nfl2k5_func_ranges / sizeof g_nfl2k5_func_ranges[0];")
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_bytes(text.encode("utf-8"))
    print("[func-ranges] %d functions -> %s" % (len(ranges), out))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generated", action="store_true", help="read ranges from translated C")
    parser.add_argument("source", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()
    if args.generated:
        main(args)
        raise SystemExit(0)
    # Retried: the analysis file can be mid-rewrite, or the output briefly held
    # open by a scanner or another session, which made builds fail at random.
    import time
    for attempt in range(6):
        try:
            main(args)
            break
        except (OSError, ValueError) as e:
            if attempt == 5:
                raise
            print("[func-ranges] retrying after: %s" % e)
            time.sleep(2)
